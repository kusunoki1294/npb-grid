function unique(values) {
  return [...new Set(values.filter(Boolean))];
}

function createPlayer(player) {
  const extra = playerExtras[player.name] ?? {};

  return {
    ...player,
    awards: unique([...(player.awards ?? []), ...(extra.awards ?? [])]),
    battingSeasonMilestones: unique([
      ...(player.battingSeasonMilestones ?? player.battingMilestones ?? []),
      ...(extra.battingSeasonMilestones ?? []),
    ]),
    battingCareerMilestones: unique([
      ...(player.battingCareerMilestones ?? []),
      ...(extra.battingCareerMilestones ?? []),
    ]),
    pitchingSeasonMilestones: unique([
      ...(player.pitchingSeasonMilestones ?? player.pitchingMilestones ?? []),
      ...(extra.pitchingSeasonMilestones ?? []),
    ]),
    pitchingCareerMilestones: unique([
      ...(player.pitchingCareerMilestones ?? []),
      ...(extra.pitchingCareerMilestones ?? []),
    ]),
    specialCategories: unique([
      ...(player.specialCategories ?? []),
      ...(extra.specialCategories ?? []),
    ]),
  };
}

export const players = rawPlayers.map(createPlayer);
